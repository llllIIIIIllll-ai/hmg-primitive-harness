#!/bin/bash
# One-shot environment setup for the HMG primitive-discovery harness.
set -euo pipefail

HERE=$(cd "$(dirname "$0")/.." && pwd)
cd "$HERE"

PYTHON=${PYTHON:-python3.10}
if ! command -v "$PYTHON" >/dev/null 2>&1; then
  echo "error: Python 3.10 is required (set PYTHON=/path/to/python3.10)" >&2
  exit 1
fi

create_venv() {
  if "$PYTHON" -m venv .venv 2>/dev/null; then
    return
  fi
  # Some distros ship Python without ensurepip. Fall back to uv.
  rm -rf .venv
  if command -v uv >/dev/null 2>&1; then
    echo "python -m venv unavailable; creating the venv with uv" >&2
    uv venv --python "$PYTHON" .venv
  else
    echo "error: cannot create a venv (install python3-venv or uv)" >&2
    exit 1
  fi
}

if [ ! -d .venv ]; then
  create_venv
fi
# shellcheck disable=SC1091
source .venv/bin/activate

pip_install() {
  if [ -x .venv/bin/pip ]; then
    .venv/bin/python -m pip install "$@"
  else
    uv pip install --python .venv/bin/python "$@"
  fi
}

pip_install --upgrade pip
pip_install -r requirements.txt

REPO=third_party/humanoidmimicgen
if [ ! -d "$REPO/.git" ]; then
  mkdir -p third_party
  git clone https://github.com/NVlabs/humanoidmimicgen.git "$REPO"
fi
# Requirements are already pinned above; do not let pip re-resolve them.
pip_install -e "$REPO" --no-deps

# The lower-body WBC policies are downloaded separately by the benchmark.
python -m humanoidmimicgen.download_wbc_policies

cat > "$HERE/env.sh" <<EOF
# Generated by scripts/bootstrap.sh
export HMG_HARNESS="$HERE"
export HMG_REPO="$HERE/$REPO"
export HMG_VENV="$HERE/.venv"
export MUJOCO_GL=egl
EOF

echo
echo "Setup complete."
echo "  source $HERE/env.sh"
echo "  $HERE/scripts/server_ctl.sh start 02_push_button 0"
